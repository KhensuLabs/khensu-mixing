def route_constants(paths: dict) -> list[str]:
    ops = []
    for path in sorted(paths):
        for method in sorted(paths[path]):
            if method.upper() in ("HEAD", "OPTIONS", "PARAMETERS"):
                continue
            readable = re.sub(r"\{([^}]*)\}", r"by_\1", path.strip("/"))
            raw = f"{method}_{readable}" if readable else f"{method}_root"
            ops.append((raw, method.upper(), path))
    names = unique_idents([o[0] for o in ops])
    lines = []
    for raw, method, path in ops:
        lines.append(f"inline constexpr Route {names[raw]}{{{cpp_str(method)}, {cpp_str(path)}}};")
    return lines


#: ENG-4: the typed structs and their fromVar parsers (~10k lines) had no
#: production caller - every caller reads juce::var through fields:: - so they
#: are no longer emitted. `--typed` brings them back for a migration to them.
EMIT_TYPED = "--typed" in sys.argv


def generate(schema_text: str) -> tuple[str, str]:
    spec = json.loads(schema_text)
    schemas: dict = spec.get("components", {}).get("schemas", {})
    struct_names = unique_idents(sorted(schemas))
    mapper = TypeMapper(schemas, struct_names)
    order = order_schemas(schemas, mapper)

    h: list[str] = [BANNER.format(src="resources/api/openapi.json"), "#pragma once", ""]
    h += [
        "#include <khensu/common/Result.h>",
        "#include <juce_core/juce_core.h>",
        "#include <cstdint>",
        "#include <optional>",
        "#include <string>",
        "#include <vector>",
        "",
        "namespace khensu::api {",
        "",
        "/// One HTTP operation of the local service.",
        "struct Route {",
        "    const char* method;",
        "    const char* path;",
        "};",
        "",
        "namespace routes {",
    ]
    h += route_constants(spec.get("paths", {}))
    h += ["} // namespace routes", "", "/// JSON property names, one namespace per schema.", "namespace fields {"]
    for n in sorted(schemas):
        props = list(schemas[n].get("properties", {}))
        if not props:
            continue
        ids = unique_idents(props)
        h.append(f"namespace {struct_names[n]} {{")
        for prop in props:
            h.append(f"inline constexpr const char* {ids[prop]} = {cpp_str(prop)};")
        h.append(f"}} // namespace {struct_names[n]}")
    h += ["} // namespace fields", ""]

    if not EMIT_TYPED:
        h += ["} // namespace khensu::api", ""]
        c_min = [BANNER.format(src="resources/api/openapi.json"),
                 "// ENG-4: routes:: and fields:: are header-only; the typed fromVar parsers",
                 "// are generated only with `python scripts/gen_cpp_api.py --typed`.",
                 "#include <khensu/ipc/generated/ApiSchema.h>", ""]
        return "\n".join(h), "\n".join(c_min)

    c: list[str] = [
        BANNER.format(src="resources/api/openapi.json"),
        "#include <khensu/ipc/generated/ApiSchema.h>",
        "",
        "namespace khensu::api {",
        "namespace {",
        "",
        "using Err = std::string;",
        "",
        "bool parseValue(const juce::var& v, double& out, Err& err, const Err& where)",
        "{",
        "    if (v.isDouble() || v.isInt() || v.isInt64()) {",
        "        out = static_cast<double>(v);",
        "        return true;",
        "    }",
        "    err = where + \": expected number\";",
        "    return false;",
        "}",
        "",
        "bool parseValue(const juce::var& v, int64_t& out, Err& err, const Err& where)",
        "{",
        "    if (v.isInt() || v.isInt64()) {",
        "        out = static_cast<int64_t>(static_cast<juce::int64>(v));",
        "        return true;",
        "    }",
        "    if (v.isDouble()) {",
        "        const double d = static_cast<double>(v);",
        "        if (std::isfinite(d) && d == std::floor(d)) {",
        "            out = static_cast<int64_t>(d);",
        "            return true;",
        "        }",
        "    }",
        "    err = where + \": expected integer\";",
        "    return false;",
        "}",
        "",
        "bool parseValue(const juce::var& v, bool& out, Err& err, const Err& where)",
        "{",
        "    if (v.isBool()) {",
        "        out = static_cast<bool>(v);",
        "        return true;",
        "    }",
        "    err = where + \": expected boolean\";",
        "    return false;",
        "}",
        "",
        "bool parseValue(const juce::var& v, juce::String& out, Err& err, const Err& where)",
        "{",
        "    if (v.isString()) {",
        "        out = v.toString();",
        "        return true;",
        "    }",
        "    err = where + \": expected string\";",
        "    return false;",
        "}",
        "",
        "bool parseValue(const juce::var& v, juce::var& out, Err&, const Err&)",
        "{",
        "    out = v;",
        "    return true;",
        "}",
        "",
        "// Declared up front so each template sees the others (a vector of optionals,",
        "// an optional vector, ...): ADL won't find them through juce/std arguments.",
        "template <typename T> auto parseValue(const juce::var& v, T& out, Err& err, const Err& where)",
        "    -> decltype(T::fromVar(v), bool());",
        "template <typename T> bool parseValue(const juce::var& v, std::optional<T>& out, Err& err, const Err& where);",
        "template <typename T> bool parseValue(const juce::var& v, std::vector<T>& out, Err& err, const Err& where);",
        "",
        "template <typename T> auto parseValue(const juce::var& v, T& out, Err& err, const Err& where)",
        "    -> decltype(T::fromVar(v), bool())",
        "{",
        "    auto r = T::fromVar(v);",
        "    if (r.is_err()) {",
        "        err = where + \" -> \" + r.error();",
        "        return false;",
        "    }",
        "    out = std::move(r.value());",
        "    return true;",
        "}",
        "",
        "template <typename T> bool parseValue(const juce::var& v, std::optional<T>& out, Err& err, const Err& where)",
        "{",
        "    if (v.isVoid() || v.isUndefined()) {",
        "        out.reset();",
        "        return true;",
        "    }",
        "    T tmp{};",
        "    if (!parseValue(v, tmp, err, where)) return false;",
        "    out = std::move(tmp);",
        "    return true;",
        "}",
        "",
        "template <typename T> bool parseValue(const juce::var& v, std::vector<T>& out, Err& err, const Err& where)",
        "{",
        "    const auto* arr = v.getArray();",
        "    if (arr == nullptr) {",
        "        err = where + \": expected array\";",
        "        return false;",
        "    }",
        "    out.clear();",
        "    out.reserve(static_cast<size_t>(arr->size()));",
        "    for (int i = 0; i < arr->size(); ++i) {",
        "        T item{};",
        "        if (!parseValue(arr->getReference(i), item, err, where + \"[\" + std::to_string(i) + \"]\"))",
        "            return false;",
        "        out.push_back(std::move(item));",
        "    }",
        "    return true;",
        "}",
        "",
        "/// Reads one property. A null counts as absent (juce::JSON parses null as void).",
        "template <typename T>",
        "bool field(const juce::DynamicObject& obj, const char* name, T& out, bool required, Err& err, const char* schema)",
        "{",
        "    const juce::var& v = obj.getProperty(juce::Identifier(name));",
        "    const Err where = Err(schema) + \".\" + name;",
        "    if (v.isVoid() || v.isUndefined()) {",
        "        if (required) {",
        "            err = where + \": missing required field\";",
        "            return false;",
        "        }",
        "        return true;",
        "    }",
        "    return parseValue(v, out, err, where);",
        "}",
        "",
        "} // namespace",
        "",
    ]

    for n in order:
        if not is_struct_schema(schemas[n]):
            continue
        sname = struct_names[n]
        d = schemas[n]
        props: dict = d.get("properties", {})
        required = set(d.get("required", []))
        ids = unique_idents(list(props))
        # A data member may not share its class's name, and should not shadow a
        # struct type used in the same class.
        taken = set(struct_names.values())
        ids = {k: (v + "_" if v in taken else v) for k, v in ids.items()}
        h.append(f"/// Schema `{n}`." if n == sname else f"/// Schema `{n}` (C++ name {sname}).")
        h.append(f"struct {sname} {{")
        member_lines = []
        for prop, p in props.items():
            ctype, nullable = mapper.map(p)
            optional = (prop not in required or nullable) and ctype != "juce::var"
            full = f"std::optional<{ctype}>" if optional else ctype
            init = "{}" if not optional else ""
            member_lines.append((prop, ids[prop], full, init, prop in required and not nullable))
            h.append(f"    {full} {ids[prop]}{init};")
        if d.get("additionalProperties") not in (None, False) or not props:
            h.append("    juce::var raw; ///< the whole object (free-form or open schema)")
        h.append(f"    static Result<{sname}> fromVar(const juce::var& v);")
        h.append("};")
        h.append("")
        mapper.emitted.add(sname)

        c.append(f"Result<{sname}> {sname}::fromVar(const juce::var& v)")
        c.append("{")
        c.append("    const auto* obj = v.getDynamicObject();")
        c.append(f"    if (obj == nullptr) return Result<{sname}>::err({cpp_str(n + ': expected object')});")
        c.append(f"    {sname} out;")
        if member_lines:
            c.append("    Err err;")
        for prop, member, _full, _init, req in member_lines:
            c.append(
                f"    if (!field(*obj, {cpp_str(prop)}, out.{member}, {'true' if req else 'false'}, err, "
                f"{cpp_str(n)})) return Result<{sname}>::err(err);"
            )
        if d.get("additionalProperties") not in (None, False) or not props:
            c.append("    out.raw = v;")
        c.append(f"    return Result<{sname}>::ok(std::move(out));")
        c.append("}")
        c.append("")

    h += ["} // namespace khensu::api", ""]
    c += ["} // namespace khensu::api", ""]
    # <cmath> for isfinite/floor in the implementation.
    c.insert(2, "#include <cmath>")
    return "\n".join(h), "\n".join(c)


def generate_job_status() -> str:
    service_root = ROOT / "local-services"
    if str(service_root) not in sys.path:
        sys.path.insert(0, str(service_root))
    from khensu_services.common.job_status import (
        CANCELLABLE_STATES,
        TERMINAL_STATES,
        JobStatus,
    )

    members = list(JobStatus)

    def enumerator(m) -> str:
        return "".join(part.capitalize() for part in m.value.split("_"))

    lines = [
        BANNER.format(src="khensu_services/common/job_status.py"),
        "#pragma once",
        "",
        "#include <juce_core/juce_core.h>",
        "#include <optional>",
        "",
        "namespace khensu::api {",
        "",
        "/// Background-job lifecycle states - the single list shared with the Python",
        "/// job stores (khensu_services/common/job_status.py) and the plugin.",
        "enum class JobStatus {",
    ]
    lines += [f"    {enumerator(m)}," for m in members]
    lines += ["};", "", "/// The wire strings, for comparisons and fake servers in tests.", "namespace job_status {"]
    lines += [f"inline constexpr const char* {ident(m.value)} = {cpp_str(m.value)};" for m in members]
    lines += ["} // namespace job_status", "", "inline const char* toString(JobStatus s) noexcept", "{",
              "    switch (s) {"]
    lines += [f"    case JobStatus::{enumerator(m)}: return {cpp_str(m.value)};" for m in members]
    lines += ["    }", "    return \"\";", "}", "",
              "/// Unknown strings (including legacy ones like \"done\") are std::nullopt.",
              "inline std::optional<JobStatus> parseJobStatus(const juce::String& s) noexcept", "{"]
    lines += [f"    if (s == {cpp_str(m.value)}) return JobStatus::{enumerator(m)};" for m in members]
    lines += ["    return std::nullopt;", "}", "", "inline bool isTerminal(JobStatus s) noexcept", "{",
              "    switch (s) {"]
    for m in members:
        lines.append(f"    case JobStatus::{enumerator(m)}: return {'true' if m in TERMINAL_STATES else 'false'};")
    lines += ["    }", "    return false;", "}", "", "inline bool isCancellable(JobStatus s) noexcept", "{",
              "    switch (s) {"]
    for m in members:
        lines.append(f"    case JobStatus::{enumerator(m)}: return {'true' if m in CANCELLABLE_STATES else 'false'};")
    lines += [
        "    }",
        "    return false;",
        "}",
        "",
        "/// True for a terminal state. An unknown string is NOT terminal: callers keep",
        "/// polling until their own deadline rather than treating it as finished.",
        "inline bool isTerminalStatus(const juce::String& s) noexcept",
        "{",
        "    const auto p = parseJobStatus(s);",
        "    return p.has_value() && isTerminal(*p);",
        "}",
        "",
        "/// True while the job is still in flight (known and not terminal).",
        "inline bool isActiveStatus(const juce::String& s) noexcept",
        "{",
        "    const auto p = parseJobStatus(s);",
        "    return p.has_value() && !isTerminal(*p);",
        "}",
        "",
        "inline bool isStatus(const juce::String& s, JobStatus expected) noexcept { return s == toString(expected); }",
        "",
        "} // namespace khensu::api",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    args = parser.parse_args()

    if not SCHEMA.exists():
        print(f"{SCHEMA.relative_to(ROOT)} is missing - run `python scripts/export_openapi.py` first.")
        return 1
    header, source = generate(SCHEMA.read_text(encoding="utf-8"))
    outputs = {HEADER: header, SOURCE: source, JOB_HEADER: generate_job_status()}

    if args.check:
        stale = [p for p, text in outputs.items()
                 if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != text]
        if stale:
            names = ", ".join(str(p.relative_to(ROOT)) for p in stale)
            print(f"Generated C++ API files are stale ({names}) - run "
                  "`python scripts/export_openapi.py && python scripts/gen_cpp_api.py`.")
            return 1
        return 0

    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {path.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
