#!/usr/bin/env python3
"""Generate the typed C++ API layer from resources/api/openapi.json.

Outputs (all GENERATED - never edit by hand):
  shared-core/include/khensu/ipc/generated/ApiSchema.h
      khensu::api::routes::*        one {method, path} constant per operation
      khensu::api::fields::<Model>  one constexpr name per JSON property, so a
                                    renamed Python field is a C++ compile error
      khensu::api::<Model>          a typed struct per component schema with
                                    `static Result<Model> fromVar(const juce::var&)`
                                    that fails (naming Model.field) on a missing
                                    required field or a wrong type
  shared-core/src/ipc/generated/ApiSchema.cpp   the fromVar implementations
  shared-core/include/khensu/ipc/generated/ApiJobStatus.h
      khensu::api::JobStatus, generated from the Python enum
      khensu_services.common.job_status (the one list of job states)

Usage (repo root):
    python scripts/export_openapi.py     # refresh the schema first
    python scripts/gen_cpp_api.py        # rewrite the generated files
    python scripts/gen_cpp_api.py --check
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "resources" / "api" / "openapi.json"
HEADER = ROOT / "shared-core" / "include" / "khensu" / "ipc" / "generated" / "ApiSchema.h"
SOURCE = ROOT / "shared-core" / "src" / "ipc" / "generated" / "ApiSchema.cpp"
JOB_HEADER = ROOT / "shared-core" / "include" / "khensu" / "ipc" / "generated" / "ApiJobStatus.h"

BANNER = (
    "// GENERATED by scripts/gen_cpp_api.py from {src} - DO NOT EDIT.\n"
    "// Regenerate: python scripts/export_openapi.py && python scripts/gen_cpp_api.py\n"
    "// clang-format off\n"
)

CPP_KEYWORDS = {
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "bool", "break",
    "case", "catch", "char", "char16_t", "char32_t", "class", "compl", "const", "constexpr",
    "const_cast", "continue", "decltype", "default", "delete", "do", "double", "dynamic_cast",
    "else", "enum", "explicit", "export", "extern", "false", "float", "for", "friend", "goto",
    "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "not_eq",
    "nullptr", "operator", "or", "or_eq", "private", "protected", "public", "register",
    "reinterpret_cast", "return", "short", "signed", "sizeof", "static", "static_assert",
    "static_cast", "struct", "switch", "template", "this", "thread_local", "throw", "true", "try",
    "typedef", "typeid", "typename", "union", "unsigned", "using", "virtual", "void", "volatile",
    "wchar_t", "while", "xor", "xor_eq",
    # Names that would shadow members/types used by the generated code.
    "fromVar", "var", "Result", "routes", "fields", "api", "khensu", "juce", "std",
    # Common macros on Windows / MSVC.
    "min", "max", "small", "near", "far", "IN", "OUT", "ERROR", "DELETE", "OPTIONAL",
}


def ident(name: str) -> str:
    out = re.sub(r"_+", "_", re.sub(r"[^0-9A-Za-z_]", "_", name))
    if not out or out[0].isdigit() or out.startswith("_"):
        out = "f_" + out.lstrip("_")  # leading _X / __ are reserved identifiers
    if out in CPP_KEYWORDS:
        out += "_"
    return out


def unique_idents(names: list[str]) -> dict[str, str]:
    """Sanitized identifier per raw name, disambiguating collisions."""
    used: set[str] = set()
    out: dict[str, str] = {}
    for n in names:
        base = ident(n)
        cand, i = base, 2
        while cand in used:
            cand = f"{base}_{i}"
            i += 1
        used.add(cand)
        out[n] = cand
    return out


def cpp_str(s: str) -> str:
    """ASCII C++ string literal (schemas are exported with ensure_ascii)."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# --------------------------------------------------------------------------
# Type mapping
# --------------------------------------------------------------------------

class TypeMapper:
    def __init__(self, schemas: dict, names: dict[str, str]):
        self.schemas = schemas
        self.names = names            # schema name -> C++ struct name
        self.emitted: set[str] = set()  # struct names defined so far (for cycles)

    def ref_name(self, ref: str) -> str:
        return ref.rsplit("/", 1)[-1]

    def is_null(self, p: dict) -> bool:
        return p.get("type") == "null"

    def map(self, p: dict) -> tuple[str, bool]:
        """(C++ type, nullable) for a property schema."""
        if not isinstance(p, dict) or not p:
            return "juce::var", False
        if "$ref" in p:
            target = self.ref_name(p["$ref"])
            if target in self.schemas and not is_struct_schema(self.schemas[target]):
                # A named scalar (e.g. the JobStatus string enum): use its own
                # type. JobStatus has its typed helpers in ApiJobStatus.h.
                return self.map({k: v for k, v in self.schemas[target].items() if k != "title"})
            if target in self.names and self.names[target] in self.emitted:
                return self.names[target], False
            return "juce::var", False  # cyclic / forward reference
        for key in ("anyOf", "oneOf"):
            if key in p:
                options = [o for o in p[key] if not self.is_null(o)]
                nullable = len(options) != len(p[key])
                if len(options) == 1:
                    t, _ = self.map(options[0])
                    return t, nullable
                return "juce::var", nullable
        if "allOf" in p and len(p["allOf"]) == 1:
            return self.map(p["allOf"][0])
        t = p.get("type")
        if isinstance(t, list):
            non_null = [x for x in t if x != "null"]
            nullable = len(non_null) != len(t)
            if len(non_null) == 1:
                q = dict(p)
                q["type"] = non_null[0]
                return self.map(q)[0], nullable
            return "juce::var", nullable
        if t == "number":
            return "double", False
        if t == "integer":
            return "int64_t", False
        if t == "boolean":
            return "bool", False
        if t == "string":
            return "juce::String", False
        if t == "array":
            inner, inner_nullable = self.map(p.get("items", {}))
            if inner_nullable and inner != "juce::var":
                inner = f"std::optional<{inner}>"
            return f"std::vector<{inner}>", False
        if t == "null":
            return "juce::var", True
        return "juce::var", False  # free-form object, enum without type, etc.

    def deps(self, p, acc: set[str]) -> None:
        if isinstance(p, dict):
            if "$ref" in p:
                acc.add(self.ref_name(p["$ref"]))
            for v in p.values():
                self.deps(v, acc)
        elif isinstance(p, list):
            for v in p:
                self.deps(v, acc)


def is_struct_schema(d: dict) -> bool:
    """Objects become structs; named scalars (string enums) do not."""
    return d.get("type", "object") == "object" or "properties" in d


def order_schemas(schemas: dict, mapper: TypeMapper) -> list[str]:
    """Dependencies first; cycles are broken at the back edge (-> juce::var)."""
    order: list[str] = []
    state: dict[str, int] = {}

    def visit(n: str) -> None:
        if state.get(n) == 2 or n not in schemas:
            return
        if state.get(n) == 1:
            return  # back edge
        state[n] = 1
        acc: set[str] = set()
        mapper.deps(schemas[n].get("properties", {}), acc)
        for d in sorted(acc):
            visit(d)
        state[n] = 2
        order.append(n)

    for n in sorted(schemas):
        visit(n)
    return order


