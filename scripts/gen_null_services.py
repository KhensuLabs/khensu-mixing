#!/usr/bin/env python3
"""Generate tests/ui/support/NullServices.h: do-nothing implementations of the
desktop service interfaces (desktop-app/Source/services/I*.h) for test doubles.

Every pure virtual gets an override that returns a neutral value. References
return function-local statics; types a test can't construct abort (a test that
reaches one must set up a real fake). Re-run after changing an interface:

    python scripts/gen_null_services.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SERVICES = ROOT / 'desktop-app' / 'Source' / 'services'
OUT = ROOT / 'tests' / 'ui' / 'support' / 'NullServices.h'

ORDER = ['IPlayback', 'IRenders', 'IStems', 'IVocalEdit', 'IAnalysisHub', 'ISessions', 'IServiceLifecycle',
         'ICloudChat', 'IShell', 'IIssues']

# Reference return types -> how to produce one.
REF_RETURNS = {
    'RenderJobManager&': 'std::abort(); // a test that renders must use FakeAppController::renderJobs()',
    'AnalysisResultModel&': 'static AnalysisResultModel m; return m;',
    'const AnalysisResult&': 'static const AnalysisResult r{}; return r;',
    'const ResultDerivedData&': 'static const ResultDerivedData d{}; return d;',
    'const GenreDatabase&': 'static const GenreDatabase g; return g;',
    'const SystemBrainDatabase&': 'static const SystemBrainDatabase b; return b;',
    'SessionManager&': 'static SessionManager m(":memory:"); return m;',
    'Midi2DeviceManager&': 'std::abort();',
    'MacroControlRouter&': 'std::abort();',
}


def default_return(ret: str) -> str:
    ret = ret.strip()
    if ret == 'void':
        return ''
    if ret in REF_RETURNS:
        return REF_RETURNS[ret]
    if ret.startswith('const ') and ret.endswith('&'):
        inner = ret[len('const '):-1].strip()
        return f'static const {inner} v{{}}; return v;'
    if ret == 'bool':
        return 'return false;'
    if ret in ('int', 'double', 'float', 'uint64_t'):
        return 'return 0;'
    if ret == 'ReportMode':
        return 'return ReportMode::EngineerDetail;'
    if ret.endswith('*'):
        return 'return nullptr;'
    return 'return {};'


def methods(text: str):
    body = text[text.index('class '):]
    for m in re.finditer(r'virtual\s+(?!~)(.+?)\s*=\s*0\s*;', body, re.S):
        decl = ' '.join(m.group(1).split())
        sig = re.match(r'(.+?)\b(\w+)\s*\((.*)\)\s*((?:const\s*)?(?:noexcept\s*)?)$', decl)
        assert sig, decl
        ret, name, args, quals = sig.groups()
        # drop default arguments (not allowed to repeat meaningfully; keep it simple)
        args = re.sub(r'\s*=\s*[^,()]+(\(\))?(?=,|$)', '', args)
        args = re.sub(r'\s*=\s*\{\}', '', args)
        yield ret.strip(), name, args.strip(), quals.strip()


def main():
    out = ['// tests/ui/support/NullServices.h',
           '// GENERATED by scripts/gen_null_services.py - do not edit by hand.',
           '// Do-nothing implementations of the desktop service interfaces, for test',
           '// doubles (see FakeAppController). Re-run the script after changing an interface.',
           '#pragma once',
           '#include <cstdlib>',
           '#include "../../../desktop-app/Source/IAppController.h"',
           '#include "../../../desktop-app/Source/analysis/ResultDerivedData.h"',
           '#include "../../../desktop-app/Source/session/AnalysisResultModel.h"',
           '#include "../../../desktop-app/Source/session/StemSeparationInfo.h"',
           '#include <khensu/analysis/AnalysisResult.h>',
           '#include <khensu/ipc/ILocalServiceBridge.h>',
           '#include <khensu/systembrain/SystemBrainDatabase.h>',
           '#include <khensu/targets/GenreDatabase.h>',
           '',
           'namespace khensu::test {',
           '']
    for iface in ORDER:
        text = (SERVICES / f'{iface}.h').read_text(encoding='utf-8')
        null = 'Null' + iface[1:]
        out.append(f'class {null} : public {iface} {{')
        out.append('  public:')
        for ret, name, args, quals in methods(text):
            q = (' ' + quals) if quals else ''
            body = default_return(ret)
            out.append(f'    {ret} {name}({args}){q} override')
            out.append('    {')
            # silence unused-parameter warnings
            params = [p.strip().split()[-1].lstrip('&*') for p in split_args(args)] if args else []
            if params:
                out.append('        juce::ignoreUnused(' + ', '.join(params) + ');')
            if body:
                out.append('        ' + body)
            out.append('    }')
        out.append('};')
        out.append('')
    out.append('} // namespace khensu::test')
    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('wrote', OUT)


def split_args(args: str):
    depth, cur, parts = 0, '', []
    for ch in args:
        if ch in '<(':
            depth += 1
        elif ch in '>)':
            depth -= 1
        if ch == ',' and depth == 0:
            parts.append(cur)
            cur = ''
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return parts


if __name__ == '__main__':
    main()
