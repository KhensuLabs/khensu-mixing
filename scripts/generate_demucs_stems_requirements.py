"""Generate the reviewed Windows Demucs dependency manifest (CFG-03).

`local-services/demucs-stems-lock.json` pins the supported Python, platform,
package roots, PyTorch CPU index, Demucs source archive, and model checkpoint.
This script resolves the pinned package roots into the committed hash-verified
manifest consumed by `packaging/install-optional-stack.ps1`.

Run after a deliberate review of that lock file:

    python scripts/generate_demucs_stems_requirements.py

Use `--check` in CI to make a changed resolver result or stale export fail
closed.  This is intentionally separate from `uv.lock`: upstream Demucs needs
a source commit installed with `--no-deps`, not its incompatible PyPI metadata.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCAL_SERVICES = ROOT / "local-services"
LOCK_PATH = LOCAL_SERVICES / "demucs-stems-lock.json"


def run_command(command: list[str], *, input_text: str) -> str:
    result = subprocess.run(
        command,
        cwd=ROOT,
        input=input_text,
        capture_output=True,
        text=True,
    )
    if result.returncode:
        detail = "\n".join(part for part in (result.stdout.strip(), result.stderr.strip()) if part)
        raise RuntimeError(f"{' '.join(command)} failed\n{detail}".rstrip())
    return result.stdout.replace("\r\n", "\n").strip()


def load_lock() -> dict[str, object]:
    payload = json.loads(LOCK_PATH.read_text(encoding="utf-8"))
    required = {"target", "indexes", "requirements_manifest", "packages", "demucs", "checkpoint"}
    missing = sorted(required - payload.keys())
    if missing:
        raise RuntimeError(f"{LOCK_PATH.relative_to(ROOT)} is missing: {', '.join(missing)}")
    if payload["target"] != {"platform": "win_amd64", "python": "3.11"}:
        raise RuntimeError("Demucs stems lock must target Windows x64 with Python 3.11.")
    if not isinstance(payload["packages"], list) or not all("==" in value for value in payload["packages"]):
        raise RuntimeError("Demucs stems lock packages must be exact name==version pins.")
    return payload


def expected_manifest(lock: dict[str, object]) -> str:
    uv = shutil.which("uv")
    if not uv:
        raise RuntimeError("Could not find 'uv' on PATH. Install uv==0.10.0 first.")
    indexes = lock["indexes"]
    assert isinstance(indexes, dict)
    packages = lock["packages"]
    assert isinstance(packages, list)
    body = run_command(
        [
            uv,
            "pip",
            "compile",
            "-",
            "--python-version",
            "3.11",
            "--python-platform",
            "windows",
            "--index-url",
            str(indexes["primary"]),
            "--extra-index-url",
            str(indexes["supplemental"]),
            "--generate-hashes",
            "--no-header",
            "--no-annotate",
        ],
        input_text="\n".join(packages) + "\n",
    )
    header = [
        "# Reviewed Windows x64 Python 3.11 Demucs stack (audit CFG-03).",
        "# GENERATED by scripts/generate_demucs_stems_requirements.py from demucs-stems-lock.json.",
        "# Install only through packaging/install-optional-stack.ps1; it installs",
        "# this manifest with --require-hashes, then verifies the pinned Demucs source archive.",
        f"--index-url {indexes['primary']}",
        f"--extra-index-url {indexes['supplemental']}",
        "",
    ]
    return "\n".join(header) + body + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the committed manifest differs from the reviewed lock")
    args = parser.parse_args()
    try:
        lock = load_lock()
        expected = expected_manifest(lock)
        manifest = LOCAL_SERVICES / str(lock["requirements_manifest"])
    except Exception as exc:  # pragma: no cover - surfaced directly to CLI/CI
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    actual = manifest.read_text(encoding="utf-8").replace("\r\n", "\n") if manifest.exists() else None
    if args.check:
        if actual != expected:
            print(f"Demucs stems manifest is stale: {manifest.relative_to(ROOT)}", file=sys.stderr)
            print("Run `python scripts/generate_demucs_stems_requirements.py` after reviewing demucs-stems-lock.json.", file=sys.stderr)
            return 1
        print("OK: reviewed Demucs stems manifest matches demucs-stems-lock.json")
        return 0

    manifest.write_text(expected, encoding="utf-8")
    print(f"wrote {manifest.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
