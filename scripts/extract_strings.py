#!/usr/bin/env python3
"""Extract translatable UI strings and maintain the i18n catalogs.

Every user-facing desktop string is wrapped in JUCE's ``TRANS("...")``
(adjacent literals concatenate, as in C++). This script:

* scans ``desktop-app/Source`` for ``TRANS(...)`` literals;
* writes ``resources/i18n/strings.template.txt`` - a JUCE LocalisedStrings
  file with every key mapped to itself, the starting point for a new locale;
* ``--check``: fails when the committed template is stale (a string was
  added/removed without regenerating), and reports per-locale coverage.

Locale files (``resources/i18n/<code>.txt``) use JUCE's format::

    language: Espanol
    countries: es
    "Render" = "Renderizar"

Keys missing from a locale fall back to English at runtime.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "desktop-app" / "Source"
I18N_DIR = ROOT / "resources" / "i18n"
TEMPLATE = I18N_DIR / "strings.template.txt"

_LITERAL = r'"(?:[^"\\\n]|\\.)*"'
TRANS_RE = re.compile(r"\b(?:NEEDS_)?TRANS\s*\(\s*((?:" + _LITERAL + r"\s*)+)\)")
LITERAL_RE = re.compile(_LITERAL)
ENTRY_RE = re.compile(r'^\s*("(?:[^"\\]|\\.)*")\s*=\s*("(?:[^"\\]|\\.)*")\s*$')

_ESCAPES = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'"}


def unescape(literal: str) -> str:
    """C++ string-literal body (without quotes) -> text."""
    out, i = [], 0
    while i < len(literal):
        ch = literal[i]
        if ch == "\\" and i + 1 < len(literal):
            out.append(_ESCAPES.get(literal[i + 1], literal[i + 1]))
            i += 2
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def strings_in(source: str) -> list[str]:
    found = []
    for match in TRANS_RE.finditer(source):
        parts = [unescape(lit[1:-1]) for lit in LITERAL_RE.findall(match.group(1))]
        text = "".join(parts)
        if text:
            found.append(text)
    return found


def extract(source_dir: Path = SOURCE_DIR) -> list[str]:
    keys: set[str] = set()
    for path in sorted(source_dir.rglob("*")):
        if path.suffix in {".cpp", ".h"}:
            keys.update(strings_in(path.read_text(encoding="utf-8", errors="replace")))
    return sorted(keys)


def render_template(keys: list[str]) -> str:
    lines = [
        "language: English (template)",
        "countries: en",
        "",
        "// GENERATED by scripts/extract_strings.py - do not edit by hand.",
        "// Copy to <code>.txt, set language/countries, and translate the right-hand sides.",
        "",
    ]
    lines += [f'"{escape(k)}" = "{escape(k)}"' for k in keys]
    return "\n".join(lines) + "\n"


def parse_locale(text: str) -> dict[str, str]:
    entries = {}
    for line in text.splitlines():
        m = ENTRY_RE.match(line)
        if m:
            entries[unescape(m.group(1)[1:-1])] = unescape(m.group(2)[1:-1])
    return entries


def coverage(keys: list[str], locale_text: str) -> float:
    if not keys:
        return 1.0
    entries = parse_locale(locale_text)
    return sum(1 for k in keys if k in entries) / len(keys)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Extract translatable UI strings and maintain the i18n catalogs.")
    parser.add_argument("--check", action="store_true", help="fail if the template is stale")
    args = parser.parse_args(argv)

    keys = extract()
    expected = render_template(keys)
    if args.check:
        actual = TEMPLATE.read_text(encoding="utf-8").replace("\r\n", "\n") if TEMPLATE.exists() else ""
        if actual != expected:
            print(f"i18n template is stale: run `python scripts/extract_strings.py` ({len(keys)} strings)",
                  file=sys.stderr)
            return 1
        for locale in sorted(I18N_DIR.glob("*.txt")):
            if locale.name == TEMPLATE.name:
                continue
            pct = 100.0 * coverage(keys, locale.read_text(encoding="utf-8"))
            print(f"{locale.stem}: {pct:.1f}% of {len(keys)} strings translated")
        print(f"OK: i18n template matches {len(keys)} TRANS() strings")
        return 0

    I18N_DIR.mkdir(parents=True, exist_ok=True)
    TEMPLATE.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {TEMPLATE.relative_to(ROOT)} ({len(keys)} strings)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
