#!/usr/bin/env python3
"""Write the public finding benchmark (OVH-10).

Reads the measured evidence the app ships - resources/calibration/
finding_evidence.json (``measure_genre_norms.py report``) and
resources/genre_norms/genre_corpus_stats.json (``stats`` / ``apply_*``) plus
the genre targets - and writes resources/calibration/BENCHMARK.md: how the
numbers were made, one table per finding, the injected defects, the corpus
per genre family, and the commands that reproduce them.

    python scripts/benchmark_report.py           # write BENCHMARK.md
    python scripts/benchmark_report.py --check   # exit 1 when it is stale

The output depends only on those three files (no dates, sorted keys), so
``scripts/check_doc_drift.py`` regenerates it in memory and fails when the
committed copy differs.
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "resources" / "calibration" / "finding_evidence.json"
STATS = ROOT / "resources" / "genre_norms" / "genre_corpus_stats.json"
TARGETS = ROOT / "resources" / "genre_norms" / "genre_targets.json"
OUT = ROOT / "resources" / "calibration" / "BENCHMARK.md"


def _pct(x: float | None) -> str:
    return "-" if x is None else f"{100.0 * x:.1f}%"


def _num(x: float | None, digits: int = 1) -> str:
    return "-" if x is None else f"{x:.{digits}f}"


def _family(gid: str, parents: dict[str, str | None]) -> str:
    seen = set()
    while parents.get(gid) and gid not in seen:
        seen.add(gid)
        gid = parents[gid]  # type: ignore[assignment]
    return gid


def _finding_table(code: str, e: dict, ev: dict) -> list[str]:
    tracks = e.get("tracks", ev["tracks"])
    source = {"full": "full pipeline (service)",
              "masking_eval": "Demucs stems, 60 s excerpts (scripts/eval_masking.py)"}.get(
        e.get("source"), "native engine")
    kind = "delivery-spec check" if e.get("kind") == "spec" else "finding"
    rows = [
        ("Graded by", f"{source}, {tracks} released tracks"),
        ("Kind", kind),
        ("Fires on released tracks" if kind == "finding" else "Released tracks missing the spec",
         f"{_pct(e.get('false_alarm_rate'))} ({e.get('fired_on', 0)} tracks)"),
        (f"Alarm (severity >= {ev['alarm_severity']:.0f})", _pct(e.get("alarm_rate"))),
    ]
    for d in e.get("detects", []):
        rows.append((f"Detects `{d['defect']}`", f"{_pct(d['rate'])} of {d['tracks']} tracks"))
    fix = e.get("fix")
    if fix:
        if fix.get("advice_only"):
            rows.append(("Fix", "advice only (nothing to render)"))
        else:
            rows.append(("Fix tried", str(fix.get("tried", 0))))
            rows.append(("Fix clears", _pct(fix.get("clears_rate"))))
            effects = fix.get("side_effects") or []
            if effects:
                rows.append(("Fix side effects", "; ".join(
                    f"`{s['code']}` {_pct(s['rate'])} ({s['tracks']}, peak guard {_pct(s.get('peak_guard_share'))})"
                    for s in effects)))
            else:
                rows.append(("Fix side effects", "none"))
    else:
        rows.append(("Fix", "not checked"))
    out = [f"### `{code}`", "", "| Measure | Value |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in rows]
    return out + [""]


def render() -> str:
    ev = json.loads(EVIDENCE.read_text(encoding="utf-8"))
    st = json.loads(STATS.read_text(encoding="utf-8"))
    targets = json.loads(TARGETS.read_text(encoding="utf-8"))["genres"]
    parents = {g["id"]: g.get("parent") for g in targets}
    windows = {g["id"]: g for g in targets}

    L: list[str] = []
    L += [
        "# Khensu finding benchmark",
        "",
        ("Generated by `scripts/benchmark_report.py` from `finding_evidence.json`, "
        "`genre_corpus_stats.json` and `genre_targets.json` - do not edit by hand; "
        "`scripts/check_doc_drift.py` fails when this file is stale."),
        "",
        "## Method",
        "",
        (f"* **Corpus.** {ev['tracks']} graded files: Creative Commons releases from archive.org "
        "(`corpus_data/genre_corpus_archive_org`, one folder per genre id) decoded whole (up to five "
        f"minutes), plus {ev.get('lossless_tracks', 0)} lossless originals of the same releases "
        "(`fetch_lossless_subset.py`). Each track is graded against its own genre's targets with no "
        "playback intent."),
        ("* **Native engine.** Findings the C++ engine can raise from the native analysis "
        "(`AudioAnalyzer` + `RecommendationEngine`, the hidden `KhensuCoreTests \"[.measure]\"` case) "
        "are graded on every track."),
        (f"* **Full pipeline.** Findings that need the deep pass (resonances, harshness, phase, sub "
        f"width, translation) are graded through the app's `AnalysisController` against the running "
        f"service (`KhensuTests \"[.measurefull]\"`) on the {ev.get('full_tracks', 0)} lossless "
        "originals (two-minute excerpts); their tables say so."),
        ("* **Stems.** `masking_collision` needs separated stems: `scripts/eval_masking.py` separates "
        "a subset of the lossless originals with the app's Demucs path (the middle 60 s) and grades "
        "each stem pair against its own bar."),
        ("* **Fires / alarm.** *Fires* is the share of released tracks a finding is raised on at any "
        f"severity. An *alarm* is a finding at severity >= {ev['alarm_severity']:.0f} (the UI's "
        "moderate band); under that it is a minor note."),
        ("* **Spec checks.** A delivery-spec check (true peak over the ceiling) reports the share of "
        "released masters that miss the spec - not a false alarm."),
        ("* **Injected defects.** For a subset of tracks the same file is graded again with a defect "
        "an engineer would call a fault (shelves, hiss, clipping, peak normalisation, DC, limiting, "
        "expansion, gain, side-channel changes, resonant and harsh bells, comb filtering). *Detects* "
        "is the share of those tracks where the finding fires on the defective copy but not on the "
        "original."),
        ("* **Fix.** For one track per genre, every defect is graded, the chain the app's Fix "
        "button would render for the finding is rendered by the service's chain runner, and the "
        "render is graded again (`KhensuTests \"[.fixchain]\"`). *Clears* is the share of tried "
        "fixes after which the finding is gone. A *side effect* is a finding the render introduced; "
        "its *peak guard* share is how many of those renders started from a file peaking over "
        "-1 dBTP, which the render's output ceiling turns down as a whole."),
    ]
    if ev.get("loudness_regraded"):
        L.append(
            f"* **Loudness regrade.** `lufs_too_quiet` / `lufs_too_loud` are regraded from each "
            "track's measured integrated loudness against the current genre windows (the engine's "
            f"severity, line for line; {ev['loudness_regraded']} graded files changed since the "
            "native run). Fix side effects come from the fix-check run as it was graded.")
    if ev.get("dynamics_regraded"):
        L.append(
            "* **LRA and crest regrade.** `lra_too_compressed`, `lra_too_dynamic`, `under_compressed` "
            "and `crest_above_genre_target` are regraded the same way from each track's measured LRA "
            "and crest factor against the current LRA windows and crest ceilings "
            f"({ev['dynamics_regraded']} graded files changed).")
    L.append("")

    L += ["## Findings at a glance", "",
          "| Finding | Graded by | Fires | Alarm | Detects (best) | Fix clears |",
          "|---|---|---|---|---|---|"]
    findings = ev["findings"]
    for code in sorted(findings):
        e = findings[code]
        det = max((d["rate"] for d in e.get("detects", [])), default=None)
        fix = e.get("fix") or {}
        clears = "advice" if fix.get("advice_only") else _pct(fix.get("clears_rate"))
        L.append(f"| `{code}` | { {'full': 'full', 'masking_eval': 'stems'}.get(e.get('source'), 'native')} | "
                 f"{_pct(e.get('false_alarm_rate'))} | {_pct(e.get('alarm_rate'))} | {_pct(det)} | "
                 f"{clears if fix else '-'} |")
    L.append("")

    L += ["## Injected defects", "", "| Defect | Findings that name it | Tracks | Already flagged | Detected |",
          "|---|---|---|---|---|"]
    for name in sorted(ev.get("defects", {})):
        d = ev["defects"][name]
        L.append(f"| `{name}` | {', '.join(f'`{c}`' for c in d['findings'])} | {d['tracks']} | "
                 f"{d['already_flagged']} | {_pct(d['detected_rate'])} |")
    L.append("")

    L += ["## Each finding", ""]
    for code in sorted(findings):
        L += _finding_table(code, findings[code], ev)

    # Corpus per genre family: the median of the measured genres' medians.
    fam: dict[str, list[tuple[str, dict]]] = {}
    for gid, s in st["genres"].items():
        fam.setdefault(_family(gid, parents), []).append((gid, s))

    def med(rows: list[tuple[str, dict]], key: str, sub: str = "median") -> float | None:
        xs = [s[key][sub] for _g, s in rows if isinstance(s.get(key), dict) and sub in s[key]]
        return statistics.median(xs) if xs else None

    L += ["## Corpus per genre family", "",
          ("Medians of the measured genres' medians. Loudness, LRA and crest are whole-track; "
          "true peak, centroid and width are two-minute excerpts."), "",
          "| Family | Genres | Tracks | LUFS | LRA (LU) | Crest (dB) | True peak (dBTP) | Centroid (Hz) | Width |",
          "|---|---|---|---|---|---|---|---|---|"]
    for f in sorted(fam):
        rows = sorted(fam[f])
        n = sum(s.get("n", 0) for _g, s in rows)
        L.append(f"| {f} | {len(rows)} | {n} | {_num(med(rows, 'lufs_whole_track'))} | "
                 f"{_num(med(rows, 'lra_whole_track'))} | {_num(med(rows, 'crest_whole_track'))} | "
                 f"{_num(med(rows, 'true_peak_dbtp'))} | {_num(med(rows, 'centroid_hz'), 0)} | "
                 f"{_num(med(rows, 'width'), 2)} |")
    L.append("")

    L += ["## Loudness windows", "",
          ("Whole-track integrated loudness per genre (one row per song, the lossless original where "
          "one exists) and the window the engine grades against. `measured` marks a window widened "
          "from these numbers (`measure_genre_norms.py apply_loudness`)."), "",
          "| Genre | Songs | p10 | Median | p90 | Window (LUFS) | |", "|---|---|---|---|---|---|---|"]
    for gid in sorted(st["genres"]):
        lw = st["genres"][gid].get("lufs_whole_track")
        g = windows.get(gid)
        if not lw or not g:
            continue
        measured = "lufs_range" in (g.get("measured") or {}).get("fields", [])
        lo, hi = g["lufs_range"]
        L.append(f"| {gid} | {lw['n']} | {_num(lw['p10'])} | {_num(lw['median'])} | {_num(lw['p90'])} | "
                 f"{_num(lo)} to {_num(hi)} | {'measured' if measured else 'hand-set'} |")
    L.append("")

    L += ["## Reproduce", "",
          ("Needs the corpus under `corpus_data/genre_corpus_archive_org/` (not in the repository; "
          "its `manifest.json` lists each track's archive.org identifier, source URL and licence), a "
          "Release build of the test binaries and, for `full` and `fixcheck`, the Python service's "
          "venv."), "",
          "```bash",
          "cmake --build build --config Release --target KhensuCoreTests KhensuTests --parallel 3",
          "python scripts/fetch_lossless_subset.py           # lossless originals",
          "python scripts/measure_genre_norms.py measure     # two-minute native metrics",
          "python scripts/measure_genre_norms.py stats",
          "python scripts/measure_genre_norms.py apply",
          "python scripts/measure_genre_norms.py evidence    # tonal shelves",
          "python scripts/measure_genre_norms.py dynamics    # whole tracks + artifact/dynamics defects",
          "python scripts/measure_genre_norms.py apply_dynamics",
          "python scripts/measure_genre_norms.py apply_crest",
          "python scripts/measure_genre_norms.py apply_loudness",
          "python scripts/measure_genre_norms.py full        # deep-pass findings through the service",
          "python scripts/measure_genre_norms.py fixcheck    # the Fix on every defect",
          "python scripts/measure_genre_norms.py report      # -> finding_evidence.json",
          "python scripts/benchmark_report.py                # -> this file",
          "```", ""]
    return "\n".join(L)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT).as_posix()} is stale - run `python scripts/benchmark_report.py`.")
            return 1
        print("BENCHMARK.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
