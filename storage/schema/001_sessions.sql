CREATE TABLE IF NOT EXISTS sessions (
    id         TEXT PRIMARY KEY,       -- UUID v4 generated by juce::Uuid
    name       TEXT NOT NULL,
    created_at TEXT NOT NULL,          -- ISO 8601 UTC e.g. "2026-06-23T14:30:00.000Z"
    updated_at TEXT NOT NULL,
    data_json  TEXT NOT NULL           -- Full Session struct serialised via juce::JSON
);

CREATE INDEX IF NOT EXISTS idx_sessions_created_at
    ON sessions(created_at DESC);
