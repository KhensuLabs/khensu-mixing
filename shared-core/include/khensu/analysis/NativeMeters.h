#pragma once
// CE-PLT-3: one native measurement engine, numerically matched to the
// Python service's shared meters (analysis/loudness.py, analysis/dsp_metrics.py)
// so the desktop can show the headline tiles the moment a file is dropped,
// before the service has answered - and so the two never disagree.
//
//   * ITU-R BS.1770-4 K-weighting (the ITU Table 1/2 coefficients at 48 kHz,
//     the De Man bilinear designs elsewhere - identical to loudness.py), from
//     analysis/KWeighting.h, the one C++ definition
//   * integrated loudness with the absolute (-70 LUFS) and relative (-10 LU)
//     gates, 400 ms blocks at a 100 ms step (pyloudnorm's block grid)
//   * short-term (3 s) and momentary (400 ms) ungated series, 100 ms hop,
//     digitally silent windows NaN
//   * EBU Tech 3342 loudness range (nearest-rank P95 - P10)
//   * 4x true peak through the same 257-tap Kaiser(9) interpolation filter
//     scipy's resample_poly uses in the service (analysis/TruePeakFilter.h,
//     shared with the desktop LoudnessAnalyzer)
//   * octave-band spectrum + tilt (Welch, Hann, 50 % overlap, "spectrum"
//     scaling - spectral_tilt_db_per_octave)
//   * stereo width clamp(2 S^2 / (M^2 + S^2), 0, 1) and mean-removed Pearson
//     correlation (dsp_metrics.stereo_width / stereo_correlation)
//
// Input is planar, contiguous float channels. Inner loops are plain loops over
// contiguous arrays with no virtual calls or branches on the hot path, so the
// compiler can vectorise the FIR dot products and the energy sums.
// Parity with Python is pinned by tests/shared-core/test_native_meters_parity.cpp
// against fixtures generated by scripts/gen_native_meter_fixtures.py.
// THREAD_CONTEXT(Any) - pure functions, no shared state.

#include <cstdint>
#include <limits>
#include <vector>

namespace khensu::native {

inline constexpr double kNaN = std::numeric_limits<double>::quiet_NaN();

/// Power-domain BS.1770 channel weights for `numChannels` (1-5 plain, 6 = 5.1,
/// 8 = 7.1 SMPTE with LFE excluded). Empty for an unsupported count.
std::vector<double> bs1770ChannelGains(int numChannels);

/// {b0, b1, b2, a1, a2} of the K-weighting shelf and RLB high-pass at `sr`
/// (analysis::kWeightingCoefficients in this layout).
struct KWeighting {
    double shelf[5];
    double rlb[5];
};
KWeighting kWeighting(double sampleRate);

struct LoudnessMeasurement {
    bool supportedLayout = true;
    /// Gated integrated loudness; NaN below one 400 ms block or when gated out.
    double integratedLufs = kNaN;
    /// Max of the short-term (3 s) / momentary (400 ms) series; NaN if none.
    double shortTermMaxLufs = kNaN;
    double momentaryMaxLufs = kNaN;
    /// EBU Tech 3342 LRA; NaN below 400 ms (0 when fewer than 2 blocks survive).
    double lra = kNaN;
    double truePeakDbtp = -240.0;
    double samplePeakDbfs = -240.0;
    /// 100 ms hop; NaN for digitally silent windows.
    std::vector<float> shortTerm;
    std::vector<float> momentary;
};

struct StereoMeasurement {
    bool stereo = false;
    double width = 0.0;       ///< 0 = mono, 1 = uncorrelated equal power
    double correlation = 1.0; ///< [-1, 1]; 1 for mono / silence
};

struct BandSpectrum {
    std::vector<double> centersHz; ///< octave centres that had bins
    std::vector<double> levelsDb;  ///< 10 log10(band energy), Welch "spectrum" scale
    double tiltDbPerOctave = 0.0;
};

struct NativeReport {
    double sampleRate = 0.0;
    int numChannels = 0;
    double durationSec = 0.0;
    LoudnessMeasurement loudness;
    StereoMeasurement stereo;
    BandSpectrum spectrum;
};

/// Short-term style ungated series: window k = [k*hop, k*hop + block), only
/// full windows (one window over everything when shorter than a block).
/// Exposed for tests; measureLoudness() calls it for 3 s and 0.4 s.
std::vector<float> loudnessSeries(const float* const* channels, int numChannels, std::int64_t numSamples,
                                  double sampleRate, double blockSec, double hopSec);

LoudnessMeasurement measureLoudness(const float* const* channels, int numChannels, std::int64_t numSamples,
                                    double sampleRate);

/// Linear 4x true peak of one channel (never below the sample peak).
double truePeakLinear(const float* x, std::int64_t numSamples);

StereoMeasurement measureStereo(const float* left, const float* right, std::int64_t numSamples);

BandSpectrum measureBandSpectrum(const float* const* channels, int numChannels, std::int64_t numSamples,
                                 double sampleRate);

/// Everything above in one call (stereo from channels 0/1 when present).
NativeReport measureAll(const float* const* channels, int numChannels, std::int64_t numSamples,
                        double sampleRate);

} // namespace khensu::native
