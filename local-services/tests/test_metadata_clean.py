"""Delivery-metadata cleaning (/metadata/clean) - the 2026-11-07 reframe of
"Strip Metadata".

The firm rule under test: workflow / personal tags go, identity and rights
stay, and AI-provenance / disclosure tags are NEVER removed, so the cleaner
can't be used to hide where audio came from.
"""
from __future__ import annotations

import mutagen
import mutagen.wave
import numpy as np
import soundfile as sf
from mutagen.id3 import COMM, PRIV, TIT2, TPE1, TSRC, TSSE, TXXX

from khensu_services.analysis.artifacts.metadata_clean import classify_tag

SR = 44100


def _tagged_wav(path, frames):
    t = np.arange(SR) / SR
    sf.write(str(path), (0.2 * np.sin(2 * np.pi * 220 * t)).astype(np.float32), SR)
    mf = mutagen.wave.WAVE(str(path))
    mf.add_tags()
    for f in frames:
        mf.tags.add(f)
    mf.save()


def test_classify_tag_rules():
    assert classify_tag("COMM::eng", "mixed late at night") == "workflow"
    assert classify_tag("TSSE", "LAME 3.100") == "workflow"
    assert classify_tag("TXXX:Software", "Studio One 6") == "workflow"
    assert classify_tag("encoder", "Lavf60") == "workflow"            # Vorbis
    assert classify_tag("\xa9too", "iTunes") == "workflow"            # MP4
    assert classify_tag("TIT2", "My Song") == "keep"
    assert classify_tag("TSRC", "USRC17607839") == "keep"
    # Provenance beats workflow: a comment naming a generator is kept.
    assert classify_tag("COMM::eng", "Generated with Suno v5") == "provenance"
    assert classify_tag("comment", "AI-generated") == "provenance"
    assert classify_tag("TXXX:c2pa_manifest", "...") == "provenance"
    assert classify_tag("TXXX:DigitalSourceType", "trainedAlgorithmicMedia") == "provenance"


def test_clean_keeps_identity_and_provenance_removes_workflow(client, tmp_path):
    src = tmp_path / "master.wav"
    _tagged_wav(src, [
        TIT2(encoding=3, text="My Song"),
        TPE1(encoding=3, text="Artist"),
        TSRC(encoding=3, text="USRC17607839"),
        COMM(encoding=3, lang="eng", desc="", text="rough mix v7, ask Sam"),
        TSSE(encoding=3, text="LAME 3.100"),
        PRIV(owner="daw.example", data=b"\x00\x01"),
        TXXX(encoding=3, desc="ai_disclosure", text="vocals AI-assisted"),
        TXXX(encoding=3, desc="comment", text="Generated by Suno v5"),
    ])
    resp = client.post("/metadata/clean", json={"file_path": str(src)})
    assert resp.status_code == 200, resp.text
    body = resp.json()
    out = body["output_path"]
    assert out.endswith("_clean.wav")
    assert body["removed_tag_count"] == 3
    assert {k.split(":")[0] for k in body["removed_tags"]} == {"COMM", "TSSE", "PRIV"}
    assert len(body["kept_provenance_tags"]) == 2

    cleaned = mutagen.File(out)
    keys = {str(k) for k in cleaned.tags.keys()}
    assert {"TIT2", "TPE1", "TSRC"} <= keys
    assert not any(k.startswith(("COMM", "TSSE", "PRIV")) for k in keys)
    # Audio is untouched.
    y0, _ = sf.read(str(src))
    y1, _ = sf.read(out)
    assert np.array_equal(y0, y1)
    # The provenance detector still sees the generator marker afterwards.
    scan = client.post("/analyze/artifacts_scan", json={"file_path": out}).json()
    assert any(row["detected"] for row in scan["service_checklist"])


def test_clean_on_untagged_file_is_a_plain_copy(client, tmp_path):
    src = tmp_path / "plain.wav"
    sf.write(str(src), np.zeros(SR, np.float32), SR)
    resp = client.post("/metadata/clean", json={"file_path": str(src)})
    assert resp.status_code == 200, resp.text
    assert resp.json()["removed_tag_count"] == 0


def test_clean_rejects_traversal_alias_and_changed_extension(client, tmp_path):
    src = tmp_path / "a.wav"
    sf.write(str(src), np.zeros(SR, np.float32), SR)
    assert client.post("/metadata/clean", json={
        "file_path": str(src), "output_path": "C:/elsewhere/out.wav"}).status_code == 403
    assert client.post("/metadata/clean", json={
        "file_path": str(src), "output_path": str(src)}).status_code == 409
    assert client.post("/metadata/clean", json={
        "file_path": str(src), "output_path": str(tmp_path / "a_clean.mp3")}).status_code == 422
    assert client.post("/metadata/clean", json={
        "file_path": str(tmp_path / "missing.wav")}).status_code == 404


def test_old_routes_are_gone(client, tmp_path):
    src = tmp_path / "a.wav"
    sf.write(str(src), np.zeros(SR, np.float32), SR)
    assert client.post("/humanize/strip_metadata", json={"file_path": str(src)}).status_code == 404
    assert client.post("/humanize/targeted", json={"file_path": str(src)}).status_code == 404
