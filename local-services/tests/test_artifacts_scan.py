# local-services/tests/test_artifacts_scan.py
"""Tests for the AI-artifact detection framework (spec §5.1): metadata-tier
service signatures, spectral-tier statistical tells, noisy-OR confidence
fusion, the service checklist, and the artifacts summary."""
import numpy as np
import pytest
import soundfile as sf

from khensu_services.analysis.artifacts import analyze_artifacts
from khensu_services.analysis.artifacts.base import KNOWN_SERVICES

SR = 44100


def _write_wav(path, y, sr=SR):
    sf.write(str(path), y.astype(np.float32), sr)
    return str(path)


def _human_like(dur=8.0, seed=11):
    """Varied levels, wandering noise floor, full bandwidth — should NOT trip
    the spectral detectors."""
    rng = np.random.default_rng(seed)
    n = int(SR * dur)
    t = np.arange(n) / SR
    level = 0.15 + 0.2 * np.abs(np.sin(2 * np.pi * 0.07 * t))     # macro-dynamics
    y = level * np.sin(2 * np.pi * 220 * t)
    y += 0.02 * rng.uniform(-1, 1, n) * (0.3 + 0.7 * rng.random(n))  # breathing floor
    y += 0.01 * rng.uniform(-1, 1, n)                              # full-band noise
    return y


def test_clean_human_like_file_reports_no_artifacts(tmp_path):
    path = _write_wav(tmp_path / "human.wav", _human_like())
    r = analyze_artifacts(path)
    assert r["verdict"] == "no_artifacts_found"
    assert r["confidence"] < 0.35
    # UIX-09: soft wording - "none of the checked artifacts", not "none exist".
    assert "None of the checked AI artifacts were found" in r["summary"]
    assert len(r["service_checklist"]) == len(KNOWN_SERVICES)
    assert all(not row["detected"] for row in r["service_checklist"])


def test_metadata_tag_attribution(tmp_path):
    import mutagen.wave
    path = _write_wav(tmp_path / "tagged.wav", _human_like())
    mf = mutagen.wave.WAVE(path)
    mf.add_tags()
    from mutagen.id3 import TXXX
    mf.tags.add(TXXX(encoding=3, desc="comment", text="Generated by Suno v5"))
    mf.save()

    r = analyze_artifacts(path)
    assert r["confidence"] >= 0.7
    assert r["verdict"] == "likely_ai"
    suno_row = next(row for row in r["service_checklist"] if row["id"] == "suno")
    assert suno_row["detected"] and suno_row["likelihood"] >= 0.9
    assert "Suno" in r["summary"]
    assert any(f["kind"] in ("metadata_tag", "byte_signature") for f in r["findings"])


def test_spectral_ceiling_detected(tmp_path):
    # Broadband noise brickwalled at 12 kHz on a 44.1k file = vocoder tell.
    rng = np.random.default_rng(5)
    n = int(SR * 8.0)
    y = 0.3 * rng.uniform(-1, 1, n)
    spec = np.fft.rfft(y)
    freqs = np.fft.rfftfreq(n, 1.0 / SR)
    spec[freqs > 12000.0] = 0.0
    y = np.fft.irfft(spec, n)
    # Keep level varied so only the ceiling detector fires.
    t = np.arange(n) / SR
    y *= 0.4 + 0.6 * np.abs(np.sin(2 * np.pi * 0.05 * t))
    path = _write_wav(tmp_path / "brickwall.wav", y)

    r = analyze_artifacts(path)
    kinds = {f["kind"] for f in r["findings"]}
    assert "spectral_ceiling" in kinds
    ceiling = next(f for f in r["findings"] if f["kind"] == "spectral_ceiling")
    assert 10000.0 <= ceiling["freq_range_hz"][0] <= 14000.0


def test_confidence_fusion_accumulates(tmp_path):
    # Flat level + constant floor + brickwall: multiple weak signals should
    # fuse into a materially higher confidence than any single one (~0.3-0.5).
    rng = np.random.default_rng(9)
    n = int(SR * 30.0)
    y = 0.25 * np.sin(2 * np.pi * 220 * np.arange(n) / SR)
    y += 0.005 * rng.uniform(-1, 1, n)   # constant audible floor
    spec = np.fft.rfft(y)
    freqs = np.fft.rfftfreq(n, 1.0 / SR)
    spec[freqs > 12000.0] = 0.0
    y = np.fft.irfft(spec, n)
    path = _write_wav(tmp_path / "flat_ai.wav", y)

    r = analyze_artifacts(path)
    assert len(r["findings"]) >= 2
    # S1: production-style observations (ceiling, constant floor, flat
    # dynamics) report signal strength in `weight` but contribute nothing;
    # fusion runs over `effective_weight`.
    max_single = max(f["effective_weight"] for f in r["findings"])
    # AUDIT-019: correlated tells (same group) count once - max, not noisy-OR;
    # only independent groups accumulate above the strongest single signal.
    from khensu_services.analysis.artifacts.engine import _group_of
    groups = {_group_of(f) for f in r["findings"] if f["effective_weight"] > 0}
    if len(groups) >= 2:
        assert r["confidence"] > max_single
    else:
        assert r["confidence"] == pytest.approx(max_single, abs=1e-3)


def test_clipping_census_included(tmp_path):
    y = _human_like()
    y[10000:10020] = 1.0
    path = _write_wav(tmp_path / "clipped.wav", y)
    r = analyze_artifacts(path)
    assert r["clipping"]["event_count"] == 1
    assert len(r["clipping"]["event_positions_sec"]) == 1
    assert r["clipping"]["event_positions_sec"][0] == pytest.approx(10000 / SR, abs=0.1)


def test_endpoint(client, tmp_path):
    path = _write_wav(tmp_path / "e.wav", _human_like(dur=4.0))
    resp = client.post("/analyze/artifacts_scan", json={"file_path": path})
    assert resp.status_code == 200
    body = resp.json()
    for key in ("confidence", "verdict", "findings", "service_checklist",
                "summary", "clipping", "detectors_run", "timeline"):
        assert key in body
    assert len(body["detectors_run"]) >= 6


def test_timeline_windows_cover_the_duration(tmp_path):
    # Audit AI-detection #3: a per-window timeline should span the whole track
    # in contiguous windows, each carrying its own fused confidence.
    y = _human_like(dur=12.0)
    path = _write_wav(tmp_path / "tl.wav", y)
    r = analyze_artifacts(path)
    tl = r["timeline"]
    assert len(tl) >= 2                       # 12s / 5s window -> 3 windows
    assert tl[0]["start_sec"] == 0.0
    # Contiguous, non-overlapping, monotonic.
    for a, b in zip(tl, tl[1:]):
        assert a["end_sec"] == pytest.approx(b["start_sec"], abs=0.01)
    assert tl[-1]["end_sec"] == pytest.approx(r["duration_sec"], abs=0.1)
    for w in tl:
        assert 0.0 <= w["confidence"] <= 1.0


def test_localized_finding_raises_only_its_window(tmp_path):
    # A finding with a time_range must contribute only to the overlapping
    # window(s), leaving other windows at the whole-file baseline.
    from khensu_services.analysis.artifacts.base import ArtifactFinding
    from khensu_services.analysis.artifacts.engine import _temporal_localization
    localized = ArtifactFinding(detector="d", kind="codec_residue", summary="s",
                                evidence="e", weight=0.8, time_range_sec=(6.0, 9.0))
    tl = _temporal_localization([localized], duration_sec=15.0, window_sec=5.0)
    # Windows: [0-5), [5-10), [10-15). Only the middle one overlaps 6-9s.
    assert tl[0]["confidence"] == 0.0
    assert tl[1]["confidence"] > 0.0
    assert tl[2]["confidence"] == 0.0


