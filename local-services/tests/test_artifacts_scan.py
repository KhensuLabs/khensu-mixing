@pytest.mark.parametrize("sr", [8000, 11025])
def test_low_rate_forensic_scan_skips_above_nyquist_bands_without_nan(tmp_path, sr):
    """CQ-01: metric-only high-frequency detectors must stay finite when a
    requested band is above the source Nyquist frequency."""
    import warnings

    t = np.arange(sr * 3) / sr
    y = (0.2 * np.sin(2 * np.pi * 440.0 * t)).astype(np.float32)
    path = _write_wav(tmp_path / f"low-{sr}.wav", y, sr=sr)

    with warnings.catch_warnings():
        warnings.simplefilter("error", RuntimeWarning)
        result = analyze_artifacts(path)

    assert np.isfinite(result["confidence"])
    assert all(np.isfinite(f["weight"]) for f in result["findings"])
