def genre_sort_key(g: dict) -> tuple:
    parent = g.get("parent", g["id"])
    is_base = g["id"] == parent
    # (parent cluster alphabetically) -> (base genre first) -> (name alphabetically)
    return (parent.lower(), 0 if is_base else 1, g["name"].lower())


def main() -> None:
    data = json.loads(TARGETS_PATH.read_text(encoding="utf-8"))
    existing_ids = {g["id"] for g in data["genres"]}

    added = 0
    for g in NEW_GENRES:
        if g["id"] in existing_ids:
            continue
        data["genres"].append(g)
        existing_ids.add(g["id"])
        added += 1

    data["genres"].sort(key=genre_sort_key)
    data["version"] = 2.1
    data["note"] = (f"SP-07 + 2026-07-09 underground-genre expansion: {len(data['genres'])} genres "
                     f"({added} added), clustered by parent family (alphabetical) with the base genre "
                     f"first in each cluster followed by alphabetical variants. GenreDatabase parser unchanged.")

    TARGETS_PATH.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(data['genres'])} genres ({added} new) to {TARGETS_PATH}")


if __name__ == "__main__":
    main()
