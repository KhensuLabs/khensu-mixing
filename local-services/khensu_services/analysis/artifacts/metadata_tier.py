# local-services/khensu_services/analysis/artifacts/metadata_tier.py
"""Metadata-tier detectors (spec §5.1, fast pass) - provenance evidence.

Two complementary detectors:

  TagSignatureDetector  — reads container tags (ID3/Vorbis/MP4/RIFF via
      mutagen) and matches tag values + encoder strings against per-service
      signature keywords. A generation service naming itself in a tag is
      the highest-precision evidence this module can produce.
  ByteSignatureDetector — parses the container's *metadata chunks only*
      (RIFF LIST/INFO, id3, iXML, bext, _PMX/XMP; AIFF text/ID3 chunks; ID3v2
      and ID3v1/APE tags of MPEG streams; FLAC Vorbis-comment/application
      blocks; Ogg header pages; MP4 moov/udta/meta/uuid boxes) and matches the
      same keywords plus embedded generation-service URLs. Catches markers in
      custom chunks/XML blobs that tag readers skip.

Audit 2026-11-06 AID-04: the keyword table used to include "bandlab" (a DAW
millions of people mix in), "deepmind" and the substring "yue-" (personal
names), matched as raw substrings over 256 KB of head+tail bytes - which for a
WAV is mostly PCM, so short keywords could collide by chance, and a "Mixed in
BandLab Studio" comment read as likely-AI 0.94. Keywords are now whole-token
regular expressions naming a *generator* (not a DAW or a company), and only
metadata chunks are scanned - never the audio payload.
"""
from __future__ import annotations

import re
import struct

from khensu_services.analysis.artifacts.base import (
    ArtifactFinding, AudioContext,
)

# service id -> whole-token regex fragments (matched case-insensitively). Each
# names a generator or its model id - never a DAW, a company or a bare word.
_SERVICE_SIGNATURES: dict[str, list[str]] = {
    "suno":          [r"suno\.(?:ai|com)", r"generated (?:by|with) suno", r"sunoai",
                      r"suno v\d+(?:\.\d+)?"],
    "udio":          [r"udio\.(?:com|ai)", r"generated (?:by|with) udio", r"udioapp"],
    # BandLab the DAW is human production; only its AI SongStarter is a tell.
    "bandlab":       [r"songstarter", r"bandlab songstarter"],
    "ace_step":      [r"ace-step", r"acestep"],
    "musicgen":      [r"musicgen", r"facebook/musicgen(?:-[a-z]+)?", r"audiocraft"],
    "heartmula":     [r"heartmula", r"heartcodec"],
    "yue_diffrhythm": [r"diffrhythm", r"m-a-p/yue(?:-[a-z0-9-]+)?", r"lyrics2song"],
    "lyria":         [r"lyria", r"synthid"],
}

# Generic AI markers that don't attribute to one service.
_GENERIC_MARKERS = [
    r"ai generated", r"ai-generated", r"generated by ai", r"text-to-music",
    r"text to music", r"aigc",
]

# Token boundaries: a keyword must not be glued to letters/digits on either side.
_TOKEN = r"(?<![a-z0-9]){kw}(?![a-z0-9])"


def _compile(patterns: list[str]) -> list[tuple[str, re.Pattern[str]]]:
    return [(p, re.compile(_TOKEN.format(kw=p), re.IGNORECASE)) for p in patterns]


_SERVICE_RES = {svc: _compile(kws) for svc, kws in _SERVICE_SIGNATURES.items()}
_GENERIC_RES = _compile(_GENERIC_MARKERS)

_URL_RE = re.compile(r"https?://[a-zA-Z0-9./_-]{4,120}")


def match_services(text: str) -> dict[str, list[str]]:
    """{service: [matched keyword, ...]} for whole-token hits in `text`."""
    hits: dict[str, list[str]] = {}
    for svc, pats in _SERVICE_RES.items():
        found = [m.group(0).lower() for _p, rx in pats for m in [rx.search(text)] if m]
        if found:
            hits[svc] = sorted(set(found))
    return hits


def match_generic(text: str) -> list[str]:
    return sorted({m.group(0).lower() for _p, rx in _GENERIC_RES for m in [rx.search(text)] if m})


class TagSignatureDetector:
    id = "metadata_tags"
    tier = "metadata"

    def scan(self, ctx: AudioContext) -> list[ArtifactFinding]:
        try:
            import mutagen
            mf = mutagen.File(ctx.file_path)
        except Exception:
            return []
        if mf is None or not getattr(mf, "tags", None):
            return []

        # Flatten every tag value into searchable text.
        parts: list[str] = []
        try:
            for key in mf.tags.keys():
                try:
                    parts.append(f"{key}={mf.tags[key]}")
                except Exception:
                    continue
        except Exception:
            return []
        blob = " | ".join(parts)

        findings: list[ArtifactFinding] = []
        for service, hits in match_services(blob).items():
            findings.append(ArtifactFinding(
                detector=self.id, kind="metadata_tag",
                summary=f"Container tags reference {service}",
                evidence="matched: " + ", ".join(hits),
                weight=0.9,
                services={service: 0.95},
                evidence_class="provenance",
            ))
        generic_hits = match_generic(blob)
        if generic_hits:
            findings.append(ArtifactFinding(
                detector=self.id, kind="metadata_tag",
                summary="Container tags carry generic AI-generation markers",
                evidence="matched: " + ", ".join(generic_hits),
                weight=0.7,
                services={"other": 0.7},
                evidence_class="provenance",
            ))
        return findings


# --- container metadata-chunk extraction --------------------------------------

_MAX_META_BYTES = 4 * 1024 * 1024     # never collect more than this
_MAX_BOX_DEPTH = 6

# RIFF/AIFF chunk ids that carry metadata (never the audio payload).
_RIFF_META = {b"LIST", b"id3 ", b"ID3 ", b"iXML", b"bext", b"_PMX", b"axml", b"INFO"}
_AIFF_META = {b"NAME", b"AUTH", b"ANNO", b"(c) ", b"COMT", b"ID3 ", b"id3 ", b"APPL"}
_MP4_META_BOXES = {b"udta", b"meta", b"ilst", b"uuid", b"XMP_", b"\xa9too", b"\xa9cmt"}
_MP4_CONTAINER_BOXES = {b"moov", b"udta", b"meta", b"trak", b"mdia", b"minf"}


def _riff_chunks(f, size: int, little: bool, meta_ids: set[bytes], start: int) -> list[bytes]:
    out: list[bytes] = []
    pos = start
    fmt = "<I" if little else ">I"
    total = 0
    while pos + 8 <= size and total < _MAX_META_BYTES:
        f.seek(pos)
        hdr = f.read(8)
        if len(hdr) < 8:
            break
        cid, clen = hdr[:4], struct.unpack(fmt, hdr[4:])[0]
        if cid in meta_ids and clen > 0:
            take = min(clen, _MAX_META_BYTES - total)
            out.append(f.read(take))
            total += take
        pos += 8 + clen + (clen & 1)
    return out


def _mp4_boxes(f, start: int, end: int, depth: int, out: list[bytes]) -> None:
    pos = start
    while pos + 8 <= end and depth <= _MAX_BOX_DEPTH and sum(map(len, out)) < _MAX_META_BYTES:
        f.seek(pos)
        hdr = f.read(8)
        if len(hdr) < 8:
            return
        blen, btype = struct.unpack(">I", hdr[:4])[0], hdr[4:]
        hlen = 8
        if blen == 1:
            ext = f.read(8)
            if len(ext) < 8:
                return
            blen, hlen = struct.unpack(">Q", ext)[0], 16
        elif blen == 0:
            blen = end - pos
        if blen < hlen:
            return
        if btype in _MP4_META_BOXES:
            f.seek(pos + hlen)
            out.append(f.read(min(blen - hlen, _MAX_META_BYTES)))
        elif btype in _MP4_CONTAINER_BOXES:
            inner = pos + hlen + (4 if btype == b"meta" else 0)
            _mp4_boxes(f, inner, pos + blen, depth + 1, out)
        pos += blen


def _syncsafe(b: bytes) -> int:
    return (b[0] << 21) | (b[1] << 14) | (b[2] << 7) | b[3]


def container_metadata_bytes(file_path: str) -> bytes:
    """Concatenated metadata chunks of `file_path` (never audio payload).

    Unknown containers return b"" - scanning PCM for keywords only adds
    false-positive surface (AID-04)."""
    out: list[bytes] = []
    try:
        with open(file_path, "rb") as f:
            f.seek(0, 2)
            size = f.tell()
            f.seek(0)
            head = f.read(12)
            if len(head) < 12:
                return b""
            if head[:4] in (b"RIFF", b"RF64", b"RIFX") and head[8:12] in (b"WAVE", b"AVI "):
                out += _riff_chunks(f, size, head[:4] != b"RIFX", _RIFF_META, 12)
            elif head[:4] == b"FORM" and head[8:12] in (b"AIFF", b"AIFC"):
                out += _riff_chunks(f, size, False, _AIFF_META, 12)
            elif head[:4] == b"fLaC":
                pos = 4
                while pos + 4 <= size:
                    f.seek(pos)
                    bh = f.read(4)
                    if len(bh) < 4:
                        break
                    last, btype = bh[0] & 0x80, bh[0] & 0x7F
                    blen = int.from_bytes(bh[1:4], "big")
                    if btype in (2, 4):          # APPLICATION, VORBIS_COMMENT
                        out.append(f.read(min(blen, _MAX_META_BYTES)))
                    pos += 4 + blen
                    if last:
                        break
            elif head[:4] == b"OggS":
                # Header pages (granule position 0) carry the comment packet;
                # audio pages are skipped.
                pos = 0
                while pos + 27 <= size and sum(map(len, out)) < _MAX_META_BYTES:
                    f.seek(pos)
                    ph = f.read(27)
                    if len(ph) < 27 or ph[:4] != b"OggS":
                        break
                    granule = struct.unpack("<q", ph[6:14])[0]
                    nseg = ph[26]
                    lacing = f.read(nseg)
                    body = sum(lacing)
                    if granule not in (0, -1):
                        break
                    out.append(f.read(body))
                    pos += 27 + nseg + body
            elif head[4:8] == b"ftyp":
                _mp4_boxes(f, 0, size, 0, out)
            else:
                # MPEG audio (and anything else): ID3v2 at the head, ID3v1 /
                # APEv2 at the tail. Nothing in between is metadata.
                if head[:3] == b"ID3":
                    tag_len = _syncsafe(head[6:10]) + 10
                    f.seek(0)
                    out.append(f.read(min(tag_len, _MAX_META_BYTES)))
                if size >= 128:
                    f.seek(size - 128)
                    v1 = f.read(128)
                    if v1[:3] == b"TAG":
                        out.append(v1)
                if size >= 32:
                    f.seek(max(0, size - 128 - 32))
                    tail = f.read(160)
                    i = tail.find(b"APETAGEX")
                    if i >= 0 and i + 32 <= len(tail):
                        ape_len = struct.unpack("<I", tail[i + 12:i + 16])[0]
                        f.seek(max(0, size - (len(tail) - i) - ape_len + 32))
                        out.append(f.read(min(ape_len, _MAX_META_BYTES)))
    except (OSError, struct.error, ValueError):
        return b"".join(out)
    return b"".join(out)


def _decode_text(blob: bytes) -> str:
    """Searchable text from metadata bytes: UTF-8 and UTF-16 (ID3 frames use
    both) views, NULs dropped."""
    views = [blob.decode("utf-8", errors="ignore")]
    for enc in ("utf-16-le", "utf-16-be"):
        try:
            views.append(blob.decode(enc, errors="ignore"))
        except Exception:
            pass
    return " ".join(v.replace("\x00", " ") for v in views)


class ByteSignatureDetector:
    id = "metadata_bytes"
    tier = "metadata"

    def scan(self, ctx: AudioContext) -> list[ArtifactFinding]:
        blob = container_metadata_bytes(ctx.file_path)
        if not blob:
            return []
        text = _decode_text(blob)

        findings: list[ArtifactFinding] = []
        for service, hits in match_services(text).items():
            findings.append(ArtifactFinding(
                detector=self.id, kind="byte_signature",
                summary=f"Container metadata chunks contain {service} markers",
                evidence="matched: " + ", ".join(hits),
                weight=0.8,
                services={service: 0.9},
                evidence_class="provenance",
            ))

        # Embedded generation-service URLs.
        urls = {m.group(0) for m in _URL_RE.finditer(text)}
        svc_urls = sorted(u for u in urls if match_services(u))
        if svc_urls:
            findings.append(ArtifactFinding(
                detector=self.id, kind="embedded_url",
                summary="Embedded URL(s) point at a generation service",
                evidence="; ".join(svc_urls[:3]),
                weight=0.75,
                services={"other": 0.5},
                evidence_class="provenance",
            ))
        return findings
