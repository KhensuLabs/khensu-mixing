# local-services/khensu_services/report/storyboard.py
"""Revision Storyboard: a client-facing, self-contained HTML page telling
the story of a revision — what changed, when, and why, in plain language.

Clients approve faster when changes are legible: instead of "v2 attached",
they get a chronological storyboard built from the session's provenance
events (applied chains, renders, exports), stripped of engineering jargon
by using each event's human summary. Fully standalone HTML (inline CSS, no
external assets) so it can be emailed or dropped in a shared folder as-is.
"""
from __future__ import annotations

import html
from datetime import datetime
from typing import Any

# Event types a client should see; internal noise (recommendation_shown,
# feedback learning, dismissals) stays out of the story.
_CLIENT_VISIBLE = {
    "chain_applied": ("Processing applied", "#00d2c4"),
    "graph_applied": ("Processing applied", "#00d2c4"),
    "recommendation_applied": ("Fix applied", "#00d2c4"),
    "snapshot_created": ("Version saved", "#7a6cff"),
    "export": ("Delivered", "#f1c40f"),
}

_PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>
  body {{ margin:0; background:#111116; color:#f0f0f5;
         font-family:'Segoe UI',system-ui,sans-serif; }}
  .wrap {{ max-width:720px; margin:0 auto; padding:36px 20px 60px; }}
  h1 {{ font-size:22px; letter-spacing:0.04em; margin-bottom:4px; }}
  .sub {{ color:#9090a8; font-size:13px; margin-bottom:28px; }}
  .card {{ background:#1a1a22; border:1px solid #26262f; border-radius:10px;
           padding:14px 16px; margin-bottom:12px; }}
  .card .type {{ font-size:11px; font-weight:700; letter-spacing:0.08em; }}
  .card .when {{ float:right; color:#9090a8; font-size:11px; }}
  .card .summary {{ margin-top:6px; font-size:14px; line-height:1.5; }}
  .empty {{ color:#9090a8; font-style:italic; }}
  .foot {{ margin-top:32px; color:#5a5a68; font-size:11px; }}
</style></head><body><div class="wrap">
<h1>{title}</h1>
<div class="sub">{subtitle}</div>
{cards}
<div class="foot">Generated by Khensu Mixing &middot; {generated}</div>
</div></body></html>
"""

_CARD = """<div class="card">
<span class="when">{when}</span>
<span class="type" style="color:{color}">{type_label}</span>
<div class="summary">{summary}</div>
</div>"""


def _fmt_when(iso: str) -> str:
    try:
        dt = datetime.fromisoformat(iso.replace("Z", "+00:00"))
        return dt.strftime("%b %d, %H:%M")
    except (ValueError, TypeError):
        return iso


def generate_storyboard(session_id: str, output_path: str,
                        title: str = "Revision Storyboard") -> dict[str, Any]:
    from khensu_services.events.db import list_events
    from .generator import strip_control_chars

    events = list_events(session_id=session_id, limit=500)
    # list_events returns newest-first; the story reads oldest-first.
    events = list(reversed(events))

    cards: list[str] = []
    for e in events:
        etype = e.get("event_type", "")
        if etype not in _CLIENT_VISIBLE:
            continue
        label, color = _CLIENT_VISIBLE[etype]
        summary = strip_control_chars(e.get("summary") or "(no description recorded)")
        cards.append(_CARD.format(
            when=html.escape(_fmt_when(e.get("created_at", ""))),
            color=color,
            type_label=html.escape(label),
            summary=html.escape(summary),
        ))

    if not cards:
        cards.append('<div class="card"><div class="summary empty">No client-visible '
                     'changes recorded for this session yet.</div></div>')

    page = _PAGE.format(
        title=html.escape(strip_control_chars(title)),
        subtitle=f"{len(cards)} change(s) in this revision — newest at the bottom",
        cards="\n".join(cards),
        generated=datetime.now().strftime("%Y-%m-%d %H:%M"),
    )
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(page)
    return {"output_path": output_path, "event_count": len(cards)}
